    /**
     * 快捷获取中文名称
     */
    fun getLocalizedName(name: String): String = getSubstanceDisplayName(name)

    /**
     * 获取物质的主要展示名称（优先返回中文标准名）
     */
    fun getSubstanceDisplayName(name: String, commonNames: List<String> = emptyList()): String {
        val trimmed = name.trim()
        if (trimmed.isEmpty()) return ""
        
        // 1. 查静态字典
        ZH_NAME_MAP[trimmed]?.let { return it }
        val foundIgnoreCase = ZH_NAME_MAP.entries.firstOrNull { it.key.equals(trimmed, ignoreCase = true) }?.value
        if (foundIgnoreCase != null) return foundIgnoreCase

        // 2. 本身包含中文汉字，直接返回
        if (containsChinese(trimmed)) return trimmed

        // 3. 从 commonNames 提取首个包含中文的项
        val zhInCommon = commonNames.firstOrNull { containsChinese(it) }
        if (zhInCommon != null) return zhInCommon.trim()

        // 4. 回退原名
        return trimmed
    }

    /**
     * 获取副标题 / 小字文本（包含原英文名与别名，排重，过滤检索专用拼音）
     */
    fun getSubstanceSecondaryText(
        name: String,
        commonNames: List<String>,
        displayName: String
    ): String {
        val list = mutableListOf<String>()
        val trimmedName = name.trim()
        // 如果显示名称是中文，且原名与显示名称不同，优先把英文原名放在副标首位
        if (trimmedName.isNotEmpty() && !trimmedName.equals(displayName, ignoreCase = true)) {
            list.add(trimmedName)
        }
        // 加入其他人类可读别名（排除 displayName 与内部拼音标记）
        for (item in commonNames) {
            val trimmed = item.trim()
            if (trimmed.isEmpty() || trimmed.equals(displayName, ignoreCase = true)) continue
            if (isPinyinToken(trimmed)) continue
            if (!list.contains(trimmed)) {
                list.add(trimmed)
            }
            if (list.size >= 5) break
        }
        return list.joinToString(", ")
    }

    private fun isPinyinToken(str: String): Boolean {
        // 如果包含中文，是合法汉字别名，不过滤
        if (containsChinese(str)) return false
        // 带单引号的隔音符拼音（如 pu'rui'ba'lin），过滤
        if (str.contains('\'')) return true
        // 全大写或含数字的化学缩写代号（如 LSD, DXM, 2C-B, PCP, MDMA），保留
        if (str.all { it.isUpperCase() || it.isDigit() || it == '-' || it == '+' || it == ' ' }) return false
        // 首字母大写的专有名词（如 Lyrica, Xanax），保留
        if (str.isNotEmpty() && str[0].isUpperCase() && !str.contains('(')) return false
        // 全小写字母且长度>=3（如 prbl, puruibalin, lrk），属于检索拼音标记，过滤
        if (str.length >= 2 && str.all { it.isLowerCase() }) return true
        // 含有括号杂项的拼音标记
        if (str.contains('(') || str.contains(')')) return true
        return false
    }

    private fun containsChinese(str: String): Boolean {
        for (ch in str) {
            if (ch in '\u4e00'..'\u9fa5') return true
        }
        return false
    }
